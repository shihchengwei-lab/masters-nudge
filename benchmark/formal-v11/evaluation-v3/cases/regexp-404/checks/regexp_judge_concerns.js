const path = require('path');
const {Linter} = require('eslint');
const rule = require(path.join(process.argv[2], 'lib/rules/no-dupe-disjunctions.ts')).default;
const linter = new Linter();
linter.defineRule('probe', rule);
const code = '/(?:a+|([ab]))(?!\\1)/';
const editedCode = '/(?:a+|([b]))(?!\\1)/';
const messages = linter.verify(code,{parserOptions:{ecmaVersion:2020},rules:{probe:'error'}});
const originalMatches = new RegExp(code.slice(1,-1)).test('a');
const editedMatches = new RegExp(editedCode.slice(1,-1)).test('a');
if (!originalMatches || editedMatches) throw new Error('Invalid backreference witness');
const column = code.indexOf('[ab]') + 2;
const wronglyRemovable = messages.some(m => m.column === column && m.endColumn === column + 1 && m.message.startsWith('Unexpected useless element.'));
const exponentialCode = '/(?:a+|[abc])+/';
const exponential = ['default','certain'].map(mode => {
  const options = mode === 'default' ? {} : {reportExponentialBacktracking:'certain'};
  const messages = linter.verify(exponentialCode,{parserOptions:{ecmaVersion:2020},rules:{probe:['error',options]}});
  return {mode,options,messages,warning:messages.some(m => /exponential backtracking/i.test(m.message))};
});
const equalCode = '/ab|(?:ab|a)/';
const equalMessages = linter.verify(equalCode,{parserOptions:{ecmaVersion:2020},rules:{probe:'error'}});
const equalColumn = equalCode.lastIndexOf('ab') + 1;
const equality = {code:equalCode,messages:equalMessages,passed:!equalMessages.some(m => m.column === equalColumn && m.message.startsWith('Unexpected useless element.') && /strict subset/.test(m.message))};
console.log('PROBE_RESULT ' + JSON.stringify({backreference:{code,editedCode,originalMatches,editedMatches,messages,wronglyRemovable,passed:!wronglyRemovable},exponential,equality}));
